-- 초기 스키마. 기준: docs/ERD.md (+ tickets.yarn_spent, 와이어프레임 "도안 바꾸기 · 털실 1올")
-- 시각은 모두 timestamptz(UTC 저장). created_at, updated_at은 BaseTimeEntity가 채우고, 시드용으로 기본값 now()를 둡니다.
-- 이 파일은 이미 적용된 뒤에는 수정하지 않습니다. 스키마 변경은 새 파일로 (docs/CODE_CONVENTION.md 6장).

-- 계정 (user)
create table users
(
    id             bigint generated by default as identity primary key,
    nickname       varchar(12)  not null,
    pin_hash       varchar(100) not null,
    is_public      boolean      not null default false,
    pin_fail_count int          not null default 0,
    locked_until   timestamptz,
    created_at     timestamptz  not null default now(),
    updated_at     timestamptz  not null default now(),
    constraint uk_users_nickname unique (nickname)
);

-- 대기실 (room, 시드)
create table rooms
(
    id                    bigint generated by default as identity primary key,
    code                  varchar(30)  not null,
    name                  varchar(30)  not null,
    slogan                varchar(100) not null,
    retrospect_question_1 varchar(100),
    retrospect_question_2 varchar(100),
    npc_empathy_copy      varchar(100),
    sort_order            int          not null,
    created_at            timestamptz  not null default now(),
    updated_at            timestamptz  not null default now(),
    constraint uk_rooms_code unique (code)
);

-- 대기실별 승차권 번호 (ticket). 발급: UPDATE ... SET last_number = last_number + 1 ... RETURNING last_number
create table room_ticket_counters
(
    room_id     bigint primary key,
    last_number int         not null default 0,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now(),
    constraint fk_room_ticket_counters_room foreign key (room_id) references rooms (id)
);

-- 상황 칩 (room, 시드)
create table situation_chips
(
    id         bigint generated by default as identity primary key,
    room_id    bigint      not null,
    code       varchar(40) not null,
    label      varchar(50) not null,
    sort_order int         not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint uk_situation_chips_code unique (code),
    constraint fk_situation_chips_room foreign key (room_id) references rooms (id)
);

-- 도안 (room, 시드)
create table patterns
(
    id         bigint generated by default as identity primary key,
    code       varchar(30) not null,
    name       varchar(30) not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint uk_patterns_code unique (code)
);

-- 승차권 = 기다림 한 건 (ticket)
create table tickets
(
    id                     bigint generated by default as identity primary key,
    room_id                bigint      not null,
    ticket_number          int         not null,
    user_id                bigint,
    guest_token            varchar(64),
    mood_chip              varchar(30),
    last_situation_chip_id bigint,
    pattern_id             bigint      not null,
    status                 varchar(10) not null,
    end_reason             varchar(20),
    started_at             timestamptz not null,
    ended_at               timestamptz,
    knitting_delivered_at  timestamptz,
    claimed_at             timestamptz,
    yarn_spent             int         not null default 0,
    created_at             timestamptz not null default now(),
    updated_at             timestamptz not null default now(),
    constraint uk_tickets_room_ticket_number unique (room_id, ticket_number),
    constraint fk_tickets_room foreign key (room_id) references rooms (id),
    constraint fk_tickets_user foreign key (user_id) references users (id),
    constraint fk_tickets_last_situation_chip foreign key (last_situation_chip_id) references situation_chips (id),
    constraint fk_tickets_pattern foreign key (pattern_id) references patterns (id),
    -- 소유자: 계정 또는 게스트 토큰 중 하나는 반드시 있어야 함
    constraint ck_tickets_owner check (user_id is not null or guest_token is not null),
    -- 종료된 기다림은 종료 사유와 종료 시각이 있어야 함
    constraint ck_tickets_ended check (status <> 'ENDED' or (end_reason is not null and ended_at is not null)),
    -- 쓴 털실 수 (남은 털실 = 지나간 열차 수 - yarn_spent)
    constraint ck_tickets_yarn_spent check (yarn_spent >= 0)
);

create index idx_tickets_guest_token on tickets (guest_token);

-- 계정 담요 조각 (blanket). 비로그인 조각은 저장하지 않음
create table blanket_pieces
(
    id            bigint generated by default as identity primary key,
    ticket_id     bigint      not null,
    user_id       bigint      not null,
    pattern_id    bigint      not null,
    ticket_number int         not null,
    waiting_name  varchar(50) not null,
    train_count   int         not null,
    end_reason    varchar(20) not null,
    created_at    timestamptz not null default now(),
    updated_at    timestamptz not null default now(),
    constraint uk_blanket_pieces_ticket unique (ticket_id),
    constraint fk_blanket_pieces_ticket foreign key (ticket_id) references tickets (id),
    constraint fk_blanket_pieces_user foreign key (user_id) references users (id),
    constraint fk_blanket_pieces_pattern foreign key (pattern_id) references patterns (id)
);

create index idx_blanket_pieces_user on blanket_pieces (user_id);
